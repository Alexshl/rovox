// design/tokens.json (the Rovox Design System export) -> src/styles/tokens.css. One source of truth for colours, type, spacing, radii.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'design', 'tokens.json'), 'utf8'));

const varName = (n) => (n.startsWith('rx-') ? `--${n}` : `--rx-${n}`);
const dark = [];
const light = [];
for (const t of tokens.color.tokens) {
  dark.push(`  ${varName(t.name)}: ${t.value.dark};`);
  light.push(`  ${varName(t.name)}: ${t.value.light};`);
}

const type = [];
for (const [name, family] of Object.entries(tokens.type.families)) type.push(`  --rx-font-${name}: ${family};`);
for (const group of tokens.type.groups)
  for (const s of group.styles) {
    type.push(`  --rx-type-${s.name}-size: ${s.fontSize};`);
    type.push(`  --rx-type-${s.name}-line: ${s.lineHeight};`);
    type.push(`  --rx-type-${s.name}-weight: ${s.fontWeight};`);
  }

const space = tokens.spacing.tokens.map((t) => `  --rx-${t.name}: ${t.value};`);
const radius = tokens.radius.tokens.map((t) => `  --rx-${t.name}: ${t.value};`);

const css = `/* SPDX-License-Identifier: AGPL-3.0-or-later */
/* Copyright (C) 2026 Rovox contributors */
/* Generated by scripts/gen-tokens.mjs from design/tokens.json. Do not edit. */
:root {
${dark.join('\n')}
${type.join('\n')}
${space.join('\n')}
${radius.join('\n')}
}

:root[data-theme='light'] {
${light.join('\n')}
}
`;

writeFileSync(join(root, 'src', 'styles', 'tokens.css'), css);
console.log('tokens.css written');
